/**
 * ATK-MD0280 触摸 SPI 引脚 (适配 F103C8T6)
 *
 *   触摸芯片 XPT2046, SPI 接口:
 *   CLK  = PA4   MISO = PA5   MOSI = PA6   CS = PA15
 */

#ifndef __ATK_MD0280_TOUCH_SPI_H
#define __ATK_MD0280_TOUCH_SPI_H

#include "atk_md0280.h"

/* ---- 引脚定义 ---- */
#define ATK_MD0280_TOUCH_SPI_CLK_PORT          GPIOA
#define ATK_MD0280_TOUCH_SPI_CLK_PIN           GPIO_PIN_4

#define ATK_MD0280_TOUCH_SPI_MI_PORT           GPIOA
#define ATK_MD0280_TOUCH_SPI_MI_PIN            GPIO_PIN_5

#define ATK_MD0280_TOUCH_SPI_MO_PORT           GPIOA
#define ATK_MD0280_TOUCH_SPI_MO_PIN            GPIO_PIN_6

#define ATK_MD0280_TOUCH_SPI_TCS_PORT          GPIOC
#define ATK_MD0280_TOUCH_SPI_TCS_PIN           GPIO_PIN_14

/* ---- IO 操作宏 ---- */
#define ATK_MD0280_TOUCH_SPI_READ_MI()         HAL_GPIO_ReadPin(ATK_MD0280_TOUCH_SPI_MI_PORT, ATK_MD0280_TOUCH_SPI_MI_PIN)

#define ATK_MD0280_TOUCH_SPI_MO(x)             HAL_GPIO_WritePin(ATK_MD0280_TOUCH_SPI_MO_PORT, ATK_MD0280_TOUCH_SPI_MO_PIN, (x) ? GPIO_PIN_SET : GPIO_PIN_RESET)

#define ATK_MD0280_TOUCH_SPI_TCS(x)            HAL_GPIO_WritePin(ATK_MD0280_TOUCH_SPI_TCS_PORT, ATK_MD0280_TOUCH_SPI_TCS_PIN, (x) ? GPIO_PIN_SET : GPIO_PIN_RESET)

#define ATK_MD0280_TOUCH_SPI_CLK(x)            HAL_GPIO_WritePin(ATK_MD0280_TOUCH_SPI_CLK_PORT, ATK_MD0280_TOUCH_SPI_CLK_PIN, (x) ? GPIO_PIN_SET : GPIO_PIN_RESET)

/* ---- 兼容原驱动旧宏名 ---- */
#define ATK_MD0280_TOUCH_SPI_MI_GPIO_PORT           ATK_MD0280_TOUCH_SPI_MI_PORT
#define ATK_MD0280_TOUCH_SPI_MI_GPIO_PIN            ATK_MD0280_TOUCH_SPI_MI_PIN
#define ATK_MD0280_TOUCH_SPI_MI_GPIO_CLK_ENABLE()   do{ __HAL_RCC_GPIOA_CLK_ENABLE(); }while(0)

#define ATK_MD0280_TOUCH_SPI_MO_GPIO_PORT           ATK_MD0280_TOUCH_SPI_MO_PORT
#define ATK_MD0280_TOUCH_SPI_MO_GPIO_PIN            ATK_MD0280_TOUCH_SPI_MO_PIN
#define ATK_MD0280_TOUCH_SPI_MO_GPIO_CLK_ENABLE()   do{ __HAL_RCC_GPIOA_CLK_ENABLE(); }while(0)

#define ATK_MD0280_TOUCH_SPI_TCS_GPIO_PORT          ATK_MD0280_TOUCH_SPI_TCS_PORT
#define ATK_MD0280_TOUCH_SPI_TCS_GPIO_PIN           ATK_MD0280_TOUCH_SPI_TCS_PIN
#define ATK_MD0280_TOUCH_SPI_TCS_GPIO_CLK_ENABLE()  do{ __HAL_RCC_GPIOC_CLK_ENABLE(); }while(0)

#define ATK_MD0280_TOUCH_SPI_CLK_GPIO_PORT          ATK_MD0280_TOUCH_SPI_CLK_PORT
#define ATK_MD0280_TOUCH_SPI_CLK_GPIO_PIN           ATK_MD0280_TOUCH_SPI_CLK_PIN
#define ATK_MD0280_TOUCH_SPI_CLK_GPIO_CLK_ENABLE()  do{ __HAL_RCC_GPIOA_CLK_ENABLE(); }while(0)

/* ---- 函数声明 ---- */
void atk_md0280_touch_spi_init(void);
uint16_t atk_md0280_touch_spi_read(uint8_t cmd);

#endif
